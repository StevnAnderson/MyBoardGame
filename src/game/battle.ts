import { getDefinition, RANGE_ORDER } from "./codex";
import type { Card, RangeBand, Team } from "./types";

/**
 * Battle resolver — an implementation of the "Battle phase" rules:
 *
 *  1. Outnumber damage (team unit totals, applied before the damage loop).
 *  2. Damage loop: Long range -> Mid range -> Melee, repeated.
 *  3. Every band is simultaneous: both sides total their damage before applying it.
 *  4. Damage is applied card-by-card left-to-right. Threatening cards must take it;
 *     non-threatening (and retreating) cards may be skipped. Excess carries over.
 *  5. At the start of every round — the first one included, right after outnumber
 *     damage — the player picks which units retreat. Retreating units do not fight
 *     and leave after any band that deals damage.
 *  6. An army reduced to structures only eats one unopposed damage loop, then loses.
 *
 * v1 resolves a single army per side (the atomic battle). Multi-army conflict
 * chains and map adjacency are intentionally out of scope — see docs/OPEN_QUESTIONS.md.
 */

export interface ArmySetup {
  label: string;
  cards: Card[];
  /** False when the player declared a retreat with no legal hex to fall back to. */
  hasRetreatHex: boolean;
}

export interface DamageApplication {
  uid: string;
  typeId: string;
  amount: number;
  hpBefore: number;
  hpAfter: number;
  destroyed: boolean;
}

export interface SideDamage {
  team: Team;
  /** Damage generated by this side in the band. */
  total: number;
  applications: DamageApplication[];
  /** Damage the attacker declined to assign. */
  forfeited: number;
}

export interface RetreatReport {
  team: Team;
  uids: string[];
}

export interface BandLog {
  band: RangeBand;
  /** Index 0 is team A's output, index 1 is team B's. */
  damage: SideDamage[];
  retreats: RetreatReport[];
}

export interface RoundLog {
  index: number;
  bands: BandLog[];
  note?: string;
}

export interface SurvivingCard {
  uid: string;
  typeId: string;
  hp: number;
  retreating: boolean;
}

export interface BattleResult {
  outnumber: (SideDamage & { source: Team }) | null;
  rounds: RoundLog[];
  winner: Team | "draw";
  reason: string;
  survivors: Record<Team, SurvivingCard[]>;
  startingUnits: Record<Team, number>;
}

/** Decides whether incoming damage is assigned to `card`. */
export type TargetPolicy = (card: Card, remaining: number, army: Card[]) => boolean;

/**
 * Default attacker behaviour: always hit threatening cards; finish off a
 * non-threatening card if the damage is enough to kill it; otherwise save the
 * damage for something that matters. If nothing threatening is left, pour it on.
 */
export const smartTargetPolicy: TargetPolicy = (card, remaining, army) => {
  const definition = getDefinition(card.typeId);
  const threatening = definition.threatening && !card.retreating;
  if (threatening) return true;
  if (remaining >= card.hp) return true;
  const stillThreatened = army.some(
    (other) =>
      other.hp > 0 && getDefinition(other.typeId).threatening && !other.retreating,
  );
  return !stillThreatened;
};

export interface BattleInput {
  a: ArmySetup;
  b: ArmySetup;
  maxRounds?: number;
  targetPolicy?: TargetPolicy;
}

/** A single card the player can choose to withdraw at the start of a round. */
export interface RetreatOption {
  uid: string;
  typeId: string;
  hp: number;
  retreating: boolean;
}

/** UIDs chosen to withdraw this round, one list per team. */
export type RetreatChoices = Record<Team, string[]>;

/** Yielded at the start of every round so the player can pick retreats. */
export interface RetreatPrompt {
  round: number;
  units: Record<Team, RetreatOption[]>;
  hasRetreatHex: Record<Team, boolean>;
  outnumber: BattleResult["outnumber"];
  /** Everything resolved so far, so a UI can show the log while the fight plays out. */
  rounds: RoundLog[];
}

const isUnit = (card: Card) => getDefinition(card.typeId).kind === "unit";
const isAlive = (card: Card) => card.hp > 0;
const TEAMS: Team[] = ["a", "b"];

export function unitCount(cards: Card[]): number {
  return cards.filter((card) => isAlive(card) && isUnit(card)).length;
}

export function totalHp(cards: Card[]): number {
  return cards.reduce((sum, card) => sum + Math.max(0, card.hp), 0);
}

/** Units that are still shooting/fighting. Retreating units are out of the fight. */
function fightingUnits(cards: Card[]): Card[] {
  return cards.filter((card) => isAlive(card) && isUnit(card) && !card.retreating);
}

/** Living units, whether or not they are already marked as retreating. */
function livingUnits(cards: Card[]): Card[] {
  return cards.filter((card) => isAlive(card) && isUnit(card));
}

function liveStructures(cards: Card[]): Card[] {
  return cards.filter((card) => isAlive(card) && !isUnit(card));
}

export function bandDamage(cards: Card[], band: RangeBand): number {
  return fightingUnits(cards)
    .filter((card) => getDefinition(card.typeId).range === band)
    .reduce((sum, card) => sum + getDefinition(card.typeId).damage, 0);
}

/** Total damage this army would deal at every range, used by previews. */
export function damageProfile(cards: Card[]): Record<RangeBand, number> {
  return {
    long: bandDamage(cards, "long"),
    mid: bandDamage(cards, "mid"),
    melee: bandDamage(cards, "melee"),
  };
}

/**
 * Apply damage to one army following the targeting rules.
 * Mutates `army` (callers work on clones).
 */
export function applyDamage(
  army: Card[],
  amount: number,
  policy: TargetPolicy = smartTargetPolicy,
): { applications: DamageApplication[]; forfeited: number } {
  const applications: DamageApplication[] = [];
  let remaining = amount;
  let selectedAny = false;

  // One pass walks the line front-to-back, wrapping until the damage is spent
  // or a full pass lands nothing.
  while (remaining > 0) {
    let hitThisPass = false;
    for (const card of army) {
      if (card.hp <= 0) continue;
      if (!policy(card, remaining, army)) continue;

      const dealt = Math.min(remaining, card.hp);
      const hpBefore = card.hp;
      card.hp -= dealt;
      remaining -= dealt;
      hitThisPass = true;
      selectedAny = true;
      applications.push({
        uid: card.uid,
        typeId: card.typeId,
        amount: dealt,
        hpBefore,
        hpAfter: card.hp,
        destroyed: card.hp <= 0,
      });
      if (remaining <= 0) break;
    }
    if (!hitThisPass) break; // walked the whole line without choosing a target
  }

  return { applications, forfeited: selectedAny ? remaining : amount };
}

function outnumberDamage(attackerUnits: number, defenderUnits: number): number {
  if (defenderUnits <= 0) return 0;
  if (attackerUnits < defenderUnits * 2) return 0;
  return Math.floor((attackerUnits - defenderUnits) / 2);
}

interface BattleState {
  sides: Record<Team, ArmySetup>;
  policy: TargetPolicy;
  maxRounds: number;
  outnumber: BattleResult["outnumber"];
  rounds: RoundLog[];
  startingUnits: Record<Team, number>;
  blockedNotes: string[];
}

function allUnitsRetreating(sides: Record<Team, ArmySetup>, team: Team): boolean {
  const units = livingUnits(sides[team].cards);
  return units.length > 0 && units.every((card) => card.retreating);
}

function retreatOption(card: Card): RetreatOption {
  return {
    uid: card.uid,
    typeId: card.typeId,
    hp: card.hp,
    retreating: card.retreating,
  };
}

function visibleRounds(state: BattleState): RoundLog[] {
  if (state.blockedNotes.length === 0) return state.rounds.slice();
  return [
    { index: -1, bands: [], note: state.blockedNotes.join(" ") },
    ...state.rounds,
  ];
}

function retreatPrompt(state: BattleState, round: number): RetreatPrompt {
  return {
    round,
    units: {
      a: livingUnits(state.sides.a.cards).map(retreatOption),
      b: livingUnits(state.sides.b.cards).map(retreatOption),
    },
    hasRetreatHex: {
      a: state.sides.a.hasRetreatHex,
      b: state.sides.b.hasRetreatHex,
    },
    outnumber: state.outnumber,
    rounds: visibleRounds(state),
  };
}

/**
 * Store this round's choices on the cards. A side with no legal retreat hex
 * cannot withdraw: every chosen unit is turned upright and the round says so.
 */
function applyRetreatChoices(
  sides: Record<Team, ArmySetup>,
  choices: RetreatChoices | undefined,
): string | null {
  const notes: string[] = [];
  for (const team of TEAMS) {
    const side = sides[team];
    const units = livingUnits(side.cards);
    const selected = new Set(
      choices?.[team] ?? units.filter((card) => card.retreating).map((card) => card.uid),
    );

    if (!side.hasRetreatHex) {
      const attempted = units.some((card) => selected.has(card.uid));
      units.forEach((card) => {
        card.retreating = false;
      });
      if (attempted) {
        notes.push(
          `${label(side.label)} declared a retreat with no legal hex — those units turned upright and fought.`,
        );
      }
      continue;
    }

    units.forEach((card) => {
      card.retreating = selected.has(card.uid);
    });
  }
  return notes.length > 0 ? notes.join(" ") : null;
}

/**
 * Step through a battle, yielding at the start of every round so the caller can
 * choose retreats — including the first round, right after outnumber damage.
 * Pass the chosen UIDs back with `iterator.next({ a: [...], b: [...] })`; the
 * return value is the final battle result. `resolveBattle` runs this to
 * completion without prompting.
 */
export function* iterateBattle(
  input: BattleInput,
): Generator<RetreatPrompt, BattleResult, RetreatChoices> {
  const state: BattleState = {
    sides: {
      a: { ...input.a, cards: input.a.cards.map((card) => ({ ...card })) },
      b: { ...input.b, cards: input.b.cards.map((card) => ({ ...card })) },
    },
    policy: input.targetPolicy ?? smartTargetPolicy,
    maxRounds: input.maxRounds ?? 20,
    outnumber: null,
    rounds: [],
    startingUnits: {
      a: unitCount(input.a.cards),
      b: unitCount(input.b.cards),
    },
    blockedNotes: [],
  };

  const { sides, policy, maxRounds, rounds, startingUnits } = state;
  const other: Record<Team, Team> = { a: "b", b: "a" };

  const finish = (winner: Team | "draw", reason: string): BattleResult => ({
    outnumber: state.outnumber,
    rounds: visibleRounds(state),
    winner,
    reason,
    survivors: {
      a: sides.a.cards.filter(isAlive).map(snapshot),
      b: sides.b.cards.filter(isAlive).map(snapshot),
    },
    startingUnits,
  });

  // Initial marks are the default for the round-1 retreat choice. A side with
  // no legal hex cannot use them, so turn those units upright before the fight.
  for (const team of TEAMS) {
    const side = sides[team];
    if (side.hasRetreatHex) continue;
    if (!side.cards.some((card) => card.retreating && isUnit(card))) continue;
    side.cards.forEach((card) => {
      if (isUnit(card)) card.retreating = false;
    });
    state.blockedNotes.push(
      `${label(side.label)} declared a retreat with no legal hex — those units turned upright and fought.`,
    );
  }

  // Mutual full withdrawal: both armies pull everything back before a shot is fired.
  if (allUnitsRetreating(sides, "a") && allUnitsRetreating(sides, "b")) {
    rounds.push({
      index: 0,
      bands: [],
      note: "Both armies withdraw every unit — no damage is dealt.",
    });
    return finish("draw", "Both armies retreated.");
  }

  // --- Outnumber damage -----------------------------------------------------
  const unitsA = unitCount(sides.a.cards);
  const unitsB = unitCount(sides.b.cards);
  const aOutnumbers = outnumberDamage(unitsA, unitsB);
  const bOutnumbers = outnumberDamage(unitsB, unitsA);

  if (aOutnumbers > 0 || bOutnumbers > 0) {
    const source: Team = aOutnumbers >= bOutnumbers ? "a" : "b";
    const amount = source === "a" ? aOutnumbers : bOutnumbers;
    const target = other[source];
    const applied = applyDamage(sides[target].cards, amount, policy);
    state.outnumber = {
      source,
      team: target,
      total: amount,
      applications: applied.applications,
      forfeited: applied.forfeited,
    };
    if (sides[target].cards.filter(isAlive).length === 0) {
      rounds.push({
        index: 0,
        bands: [],
        note: "Outnumber damage alone ended the battle.",
      });
      return finish(source, "Outnumbered and wiped out before the damage loop.");
    }
  }

  // --- Damage loop ----------------------------------------------------------
  let winner: Team | "draw" | null = null;
  let reason = "";
  let roundIndex = 0;

  while (roundIndex < maxRounds) {
    roundIndex += 1;
    const round: RoundLog = { index: roundIndex, bands: [] };

    // Every round opens with a retreat decision. The prompt only needs to
    // appear while both sides still have units that could withdraw.
    const aUnits = livingUnits(sides.a.cards);
    const bUnits = livingUnits(sides.b.cards);
    if (aUnits.length > 0 && bUnits.length > 0) {
      const choices = yield retreatPrompt(state, roundIndex);
      const note = applyRetreatChoices(sides, choices);
      if (note) round.note = note;
    }

    // Both sides pulling every unit back ends the fight before any band fires.
    if (allUnitsRetreating(sides, "a") && allUnitsRetreating(sides, "b")) {
      round.note =
        round.note ?? "Both armies withdraw every unit — no damage is dealt.";
      rounds.push(round);
      return finish("draw", "Both armies retreated.");
    }

    // Structures-only: the opponent gets one unopposed loop, then it's over.
    const aFights = fightingUnits(sides.a.cards).length > 0;
    const bFights = fightingUnits(sides.b.cards).length > 0;
    if (!aFights && !bFights) {
      rounds.push(round);
      winner = "draw";
      reason = "Neither side has a unit left to fight with.";
      break;
    }
    if (aFights !== bFights) {
      const attacker: Team = aFights ? "a" : "b";
      const defender: Team = other[attacker];
      const hasStructures = liveStructures(sides[defender].cards).length > 0;
      if (hasStructures) {
        round.note = `${label(sides[defender].label)} is down to structures — one unopposed damage loop.`;
        for (const band of RANGE_ORDER) {
          const total = bandDamage(sides[attacker].cards, band);
          const applied = applyDamage(sides[defender].cards, total, policy);
          round.bands.push({
            band,
            damage: [
              { team: attacker, total, ...applied },
              { team: defender, total: 0, applications: [], forfeited: 0 },
            ],
            retreats: [],
          });
        }
      }
      rounds.push(round);
      winner = attacker;
      reason = hasStructures
        ? "Reduced to structures after one unopposed damage loop."
        : "All units defeated or withdrawn.";
      break;
    }

    let damagedThisRound = false;
    let retreatedThisRound = false;

    for (const band of RANGE_ORDER) {
      // Both totals are locked in before either is applied — damage is simultaneous.
      const aTotal = bandDamage(sides.a.cards, band);
      const bTotal = bandDamage(sides.b.cards, band);
      const aApplied = applyDamage(sides.b.cards, aTotal, policy);
      const bApplied = applyDamage(sides.a.cards, bTotal, policy);

      const dealt = aApplied.applications.reduce((sum, entry) => sum + entry.amount, 0) +
        bApplied.applications.reduce((sum, entry) => sum + entry.amount, 0);
      if (dealt > 0) damagedThisRound = true;

      const retreats: RetreatReport[] = [];
      if (dealt > 0) {
        for (const team of TEAMS) {
          const leaving = sides[team].cards.filter(
            (card) => card.retreating && card.hp > 0 && isUnit(card),
          );
          if (leaving.length === 0) continue;
          sides[team].cards = sides[team].cards.filter(
            (card) => !(card.retreating && card.hp > 0 && isUnit(card)),
          );
          retreats.push({ team, uids: leaving.map((card) => card.uid) });
          retreatedThisRound = true;
        }
      }

      round.bands.push({
        band,
        damage: [
          { team: "a", total: aTotal, ...aApplied },
          { team: "b", total: bTotal, ...bApplied },
        ],
        retreats,
      });
    }

    rounds.push(round);

    const aStillFights = fightingUnits(sides.a.cards).length > 0;
    const bStillFights = fightingUnits(sides.b.cards).length > 0;
    if (!aStillFights && !bStillFights) {
      winner = "draw";
      reason = "Neither side has a unit left to fight with.";
      break;
    }
    if (!aStillFights || !bStillFights) {
      const beaten: Team = !aStillFights ? "a" : "b";
      // If they still hold structures, the next loop gives the winner one
      // unopposed pass before the battle is called.
      if (liveStructures(sides[beaten].cards).length === 0) {
        winner = other[beaten];
        reason = "All units defeated or withdrawn.";
        break;
      }
    }

    if (!damagedThisRound && !retreatedThisRound) {
      winner = "draw";
      reason = "A full damage loop dealt nothing — the battle stalls.";
      break;
    }
  }

  if (winner === null) {
    winner = "draw";
    reason = `Round limit reached (${maxRounds}) without a decision.`;
  }

  return finish(winner, reason);
}

/**
 * Synchronous convenience wrapper: resolves a whole battle without asking for
 * retreat choices. Existing retreat marks on the input cards are kept, which is
 * what the automated tests and non-interactive callers expect.
 */
export function resolveBattle(input: BattleInput): BattleResult {
  const iterator = iterateBattle(input);
  let step = iterator.next();
  while (!step.done) {
    const prompt = step.value;
    step = iterator.next({
      a: prompt.units.a.filter((unit) => unit.retreating).map((unit) => unit.uid),
      b: prompt.units.b.filter((unit) => unit.retreating).map((unit) => unit.uid),
    });
  }
  return step.value;
}

function snapshot(card: Card): SurvivingCard {
  return { uid: card.uid, typeId: card.typeId, hp: card.hp, retreating: card.retreating };
}

function label(value: string): string {
  return value || "Army";
}
